function quickBiteCategory(item) {
  if (QUICK_BITE_CATEGORY_BY_TITLE[item.title]) return QUICK_BITE_CATEGORY_BY_TITLE[item.title];
  const title = String(item.title || '').toLowerCase();
  if (/chaat/.test(title)) return 'Chaat';
  if (/yogurt|curd|dahi/.test(title)) return 'Yogurt Bowl';
  if (/paneer|cheese|feta|mozzarella/.test(title)) return 'Protein Bite';
  if (/nut|peanut|almond|date|trail mix/.test(title)) return 'Nuts & Seeds';
  if (item.category === 'fruit') return 'Fruit Pairing';
  if (item.category === 'fresh') return 'Fresh Combo';
  return item.cuisine === 'Indian' ? 'Indian Snack' : 'Light Snack';
}

